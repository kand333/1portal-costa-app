/**
 * Reads the samples read from portals (`valuation-samples.csv`, `valuation-rent-samples.csv`), calibrates the base price
 * of each city and the coefficient of each sector, validates the result and writes the data migration.
 *
 * Run from `apps/api`: `npx tsx prisma/data/build-valuation-update.ts [--write]`. Without `--write` it only prints.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { calibrateCity, trimmedMedian, validate, type ValuationSample } from "../../src/services/valuation-calibration";

const dataDirectory = __dirname;
const MIGRATION = join(dataDirectory, "..", "migrations", "20261127120000_calibrate_valuation_sectors", "migration.sql");
const CAPTURED_ON = "2026-11-27";
const UF_VALUE = 41_412;

/** Approximate centre of each sector (OpenStreetMap neighbourhood nodes where they exist; the rest by eye: review them). */
const CENTRES: Record<string, [number, number]> = {
  "Centro de Concepción": [-36.827, -73.0503],
  "Barrio Oriente - Las Tres Pascualas": [-36.8225, -73.034],
  "Barrio Poniente": [-36.833, -73.061],
  "Barrio Universitario": [-36.831, -73.035],
  "Bajo Tucapel": [-36.826, -73.056],
  "Barrio Norte": [-36.813, -73.042],
  "Pedro de Valdivia": [-36.8468, -73.0513],
  "Lomas de San Sebastián": [-36.7802, -73.0491],
  "Lomas de San Andrés": [-36.7921, -73.0578],
  Collao: [-36.8182, -73.0219],
  "Lorenzo Arenas": [-36.806, -73.03],
  Andalién: [-36.8176, -73.06],
  Andalué: [-36.842, -73.105],
  "Huertos Familiares": [-36.853, -73.113],
  "Portal San Pedro": [-36.842, -73.118],
  "Villa San Pedro - Bayona": [-36.845, -73.1],
  Michaihue: [-36.82, -73.096],
};

const lines = (file: string) => readFileSync(join(dataDirectory, file), "utf8").trim().split("\n").slice(1);

function loadSamples(): ValuationSample[] {
  const seen = new Set<string>();
  const samples: ValuationSample[] = [];
  for (const line of lines("valuation-samples.csv")) {
    const [platform, commune, sector, type, id, uf, area, beds, capturedOn] = line.split(",");
    const priceUf = Number(uf);
    const squareMeters = Number(area);
    const perSquareMeter = priceUf / squareMeters;
    if (!(priceUf > 0) || squareMeters < 25 || perSquareMeter < 15 || perSquareMeter > 150) continue;
    const key = [commune, sector, type, priceUf, squareMeters].join("|");
    if (seen.has(key)) continue;
    seen.add(key);
    samples.push({
      platform: platform!,
      url: `https://www.portalinmobiliario.com/MLC-${id}`,
      capturedOn: capturedOn!,
      city: commune!,
      commune: commune!,
      sector: sector!,
      propertyType: type as ValuationSample["propertyType"],
      operation: "SALE",
      priceUf,
      rentClp: null,
      area: squareMeters,
      bedrooms: beds ? Number(beds) : null,
      constructionYear: null,
      isNewProject: false,
    });
  }
  return samples;
}

const escape = (text: string) => text.replaceAll("'", "''");
const round = (value: number, digits: number) => Math.round(value * 10 ** digits) / 10 ** digits;

const samples = loadSamples();
const sql: string[] = ["-- Calibration of the reference table with listings read from Portal Inmobiliario on " + CAPTURED_ON + ".", "-- Generated by prisma/data/build-valuation-update.ts from prisma/data/valuation-samples.csv."];

for (const city of ["Concepción", "San Pedro de la Paz"]) {
  const inCity = samples.filter((sample) => sample.city === city);
  const calibration = calibrateCity(inCity);
  const check = validate(inCity);
  console.log(`\n== ${city}: ${inCity.length} samples; base apartment ${round(calibration.base.APARTMENT ?? 0, 1)}, house ${round(calibration.base.HOUSE ?? 0, 1)} UF/m²`);
  console.log(`   leave-one-out: n=${check.tested}, MAPE ${(check.mape * 100).toFixed(1)} %, within ±20 % ${(check.within20 * 100).toFixed(0)} %`);
  for (const sector of calibration.sectors.sort((a, b) => b.coefficient - a.coefficient)) {
    const apartment = sector.medians.APARTMENT;
    const house = sector.medians.HOUSE;
    console.log(
      `   ${sector.sector.padEnd(38)} n=${String(sector.count).padStart(3)}  coef ${sector.coefficient.toFixed(2)} (raw ${sector.rawCoefficient?.toFixed(2) ?? "-"})  apt ${apartment ? round(apartment.median, 1) + "/" + apartment.count : "-"}  house ${house ? round(house.median, 1) + "/" + house.count : "-"}`,
    );
  }

  const apartmentBase = round(calibration.base.APARTMENT ?? 0, 1);
  const houseBase = round(calibration.base.HOUSE ?? 0, 1);
  sql.push(
    `\n-- ${city}: base prices (UF per m²) from the median of the sectors' medians.`,
    `UPDATE "ValuationCity" SET "apartmentUfPerM2" = ${apartmentBase || "\"apartmentUfPerM2\""}, "houseUfPerM2" = ${houseBase || "\"houseUfPerM2\""}, "updatedAt" = CURRENT_TIMESTAMP WHERE "name" = '${escape(city)}';`,
    `DELETE FROM "ValuationSector" WHERE "cityId" = (SELECT "id" FROM "ValuationCity" WHERE "name" = '${escape(city)}');`,
    `INSERT INTO "ValuationSector" ("id", "cityId", "name", "commune", "latitude", "longitude", "coefficient", "note", "source", "updatedAt")`,
    `SELECT gen_random_uuid(), city."id", sector."name", '${escape(city)}', sector."latitude", sector."longitude", sector."coefficient", sector."note", sector."source", CURRENT_TIMESTAMP`,
    `FROM (SELECT "id" FROM "ValuationCity" WHERE "name" = '${escape(city)}') AS city, (VALUES`,
    calibration.sectors
      .map((sector) => {
        const [latitude, longitude] = CENTRES[sector.sector] ?? [0, 0];
        const note = `Muestreo ${CAPTURED_ON} (Portal Inmobiliario): ${sector.count} avisos. Centro aproximado: revisar.`;
        const source = sector.count >= 8 ? "muestreo" : "estimado";
        return `    ('${escape(sector.sector)}', ${latitude}, ${longitude}, ${round(sector.coefficient, 2)}, '${escape(note)}', '${source}')`;
      })
      .join(",\n"),
    `) AS sector ("name", "latitude", "longitude", "coefficient", "note", "source");`,
  );
}

// Monthly rent as a share of the sale price, from rent listings against the sale medians of the same type.
const rentRows = lines("valuation-rent-samples.csv").map((line) => line.split(","));
const saleMedian = (type: "APARTMENT" | "HOUSE") =>
  trimmedMedian(samples.filter((sample) => sample.city === "Concepción" && sample.propertyType === type).map((sample) => sample.priceUf! / sample.area));
for (const type of ["APARTMENT", "HOUSE"] as const) {
  const rentPerSquareMeter = trimmedMedian(rentRows.filter((row) => row[2] === type).map((row) => Number(row[3]) / Number(row[4])));
  const sale = saleMedian(type);
  if (rentPerSquareMeter && sale) {
    console.log(`\nRent ${type}: median ${Math.round(rentPerSquareMeter)} CLP/m²; sale median ${round(sale, 1)} UF/m² → monthly yield ${((rentPerSquareMeter / (sale * UF_VALUE)) * 100).toFixed(2)} %`);
  }
}

if (process.argv.includes("--write")) {
  writeFileSync(MIGRATION, sql.join("\n") + "\n", "utf8");
  console.log(`\nWrote ${MIGRATION}`);
}
